#!/usr/bin/env bash
# CI only: point Terraform at the Azure Storage remote state with Entra ID (OIDC)
# authentication and run 'terraform init'. Milestone 1 keeps local state because the
# backend block lives in a generated, git-ignored backend_override.tf.
#
# Required environment: TFSTATE_STORAGE_ACCOUNT, TFSTATE_CONTAINER, ARM_CLIENT_ID,
# ARM_TENANT_ID, ARM_SUBSCRIPTION_ID. Shared keys, SAS tokens and client secrets are refused.
set -euo pipefail
cd "${TF_DIR:-$(dirname "$0")/../..}"

STATE_KEY="${TFSTATE_KEY:-atlas-platform-foundation/dev.tfstate}"
for v in TFSTATE_STORAGE_ACCOUNT TFSTATE_CONTAINER ARM_CLIENT_ID ARM_TENANT_ID ARM_SUBSCRIPTION_ID; do
  [[ -n "${!v:-}" ]] || { echo "ERROR: ${v} is not set"; exit 2; }
done
for v in ARM_ACCESS_KEY ARM_SAS_TOKEN ARM_CLIENT_SECRET ARM_CLIENT_CERTIFICATE_PATH ARM_CLIENT_CERTIFICATE ARM_CLIENT_CERTIFICATE_PASSWORD; do
  [[ -z "${!v:-}" ]] || { echo "ERROR: ${v} is set; this backend uses OIDC/Entra ID only"; exit 2; }
done
[[ "${TFSTATE_STORAGE_ACCOUNT}" =~ ^[a-z0-9]{3,24}$ ]] || { echo "ERROR: invalid TFSTATE_STORAGE_ACCOUNT"; exit 2; }
[[ "${STATE_KEY}" =~ ^[a-z0-9./_-]+\.tfstate$ ]] || { echo "ERROR: invalid TFSTATE_KEY"; exit 2; }

cat > backend_override.tf <<'HCL'
# Generated by scripts/ci/backend-init.sh (git-ignored). Do not commit.
terraform {
  backend "azurerm" {}
}
HCL

terraform init -input=false -no-color -reconfigure \
  -backend-config="storage_account_name=${TFSTATE_STORAGE_ACCOUNT}" \
  -backend-config="container_name=${TFSTATE_CONTAINER}" \
  -backend-config="key=${STATE_KEY}" \
  -backend-config="use_azuread_auth=true" \
  -backend-config="use_oidc=true"
